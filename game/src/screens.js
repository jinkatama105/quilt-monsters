const CODEX_PAGE_ROWS = 4, CODEX_PAGE_SIZE = CODEX_PAGE_ROWS * 4;
let codexPage = 0;
export function codexPageCount() { return Math.ceil(SPECIES_LIST.length / CODEX_PAGE_SIZE); }
