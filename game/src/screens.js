function centerText(ctx, text, x, y, font, color) {
  ctx.font = font; ctx.fillStyle = color; ctx.textAlign = 'center';
  ctx.fillText(text, x, y); ctx.textAlign = 'left';
}

// ---------------------------------------------------------------- title
export function drawTitle(ctx, t) {
  // New style: real Ghibli watercolor backdrop (forest map, cover-fit) under a
  // dark green->indigo wash, so the painted UI reads as part of the world.
  const bg = titleBgImage();
  if (bg) {
    const s = Math.max(VIEW_W / bg.width, VIEW_H / bg.height);
    const w = bg.width * s, h = bg.height * s;
    ctx.drawImage(bg, (VIEW_W - w) / 2, (VIEW_H - h) / 2, w, h);
  } else {
    const g = ctx.createLinearGradient(0, 0, 0, VIEW_H);
    g.addColorStop(0, '#cfeef7'); g.addColorStop(0.6, '#e8f7ee'); g.addColorStop(1, '#fff3c4');
    ctx.fillStyle = g; ctx.fillRect(0, 0, VIEW_W, VIEW_H);
  }
  // wash: keep painting visible in the middle, darken top (title) & bottom (footer)
  const wash = ctx.createLinearGradient(0, 0, 0, VIEW_H);
  wash.addColorStop(0, 'rgba(255,246,220,0.30)'); wash.addColorStop(0.35, 'rgba(255,246,220,0.10)');
  wash.addColorStop(0.75, 'rgba(255,214,110,0.15)'); wash.addColorStop(1, 'rgba(255,214,110,0.30)');
  ctx.fillStyle = wash; ctx.fillRect(0, 0, VIEW_W, VIEW_H);

  // drifting fireflies (watercolor-safe: soft, low alpha)
  for (let i = 0; i < 10; i++) {
    const x = (i * 173 + t * (8 + i * 2)) % (VIEW_W + 80) - 40;
    const y = 140 + (i * 97) % 520 + Math.sin(t * 0.9 + i) * 18;
    ctx.globalAlpha = 0.12 + 0.06 * Math.sin(t * 2 + i);
    ctx.fillStyle = i % 3 === 0 ? 'rgba(176,222,255,0.9)' : 'rgba(230,245,205,0.9)';
    ctx.beginPath(); ctx.arc(x, y, 4 + (i % 3) * 3, 0, 7); ctx.fill();
    ctx.globalAlpha = 1;
  }

  // crest: three heroes in the intro pose, on the painting with soft shadows
  // hero painting already shows the three Tribus — no vector sprites on top

  // title plate — Muse watercolor frame (falls back to procedural double line)
  if (!drawSlice(ctx, 'title_frame', VIEW_W / 2 - 400, 90, 800, 170, 32, 0.95)) {
    ctx.save();
    roundRect(ctx, VIEW_W / 2 - 400, 90, 800, 170, 18);
    ctx.fillStyle = 'rgba(255,246,220,0.85)'; ctx.fill();
    ctx.strokeStyle = 'rgba(91,70,54,0.90)'; ctx.lineWidth = 3; ctx.stroke();
    ctx.restore();
  }
  centerText(ctx, 'QUILT MONSTER SHOWDOWN', VIEW_W / 2, 168, 'bold 58px monospace', '#3b2c17');
  centerText(ctx, 'explore · battle · capture the three Tribus', VIEW_W / 2, 212, '18px monospace', '#2e7d32');

  const pulse = 1 + Math.sin(t * 3) * 0.02;
  ctx.save(); ctx.translate(VIEW_W / 2, 300); ctx.scale(pulse, pulse);
  drawHudButton(ctx, -160, -26, 320, 56, '▶  MULAI — PRESS ENTER / CLICK', true);
  ctx.restore();

  centerText(ctx, 'WASD / arrows walk · click sparkles for loot · C = Codex · mouse picks battle actions',
    VIEW_W / 2, 362, '14px monospace', '#6d5b3c');
  centerText(ctx, 'a fully procedural creature quest — art & sound generated by code',
    VIEW_W / 2, VIEW_H - 26, '13px monospace', '#6d5b3c');
}

// lazy image cache for the title backdrop (module scope so it loads once)
let _titleBg = undefined;
function titleBgImage() {
  if (_titleBg === undefined) {
    _titleBg = null;
    const img = new Image();
    img.onload = () => { _titleBg = img; };
    img.src = 'assets/title_hero.png?v=quilt4';
  }
  return _titleBg;
}

