export function victoryScore(result) {
  const timeBonus = Math.max(0, 12000 - Math.round(result.time) * 4);
  const stepPenalty = result.steps * 2;
  const captureBonus = result.captures * 350;
  const winsBonus = result.wins * 200;
  return Math.max(0, timeBonus + captureBonus + winsBonus - stepPenalty + 5000);
}

function fmtTime(s) {
  const m = Math.floor(s / 60), sec = Math.floor(s % 60);
  return `${m}:${String(sec).padStart(2, '0')}`;
}

