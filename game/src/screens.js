function centerText(ctx, text, x, y, font, color) {
  ctx.font = font; ctx.fillStyle = color; ctx.textAlign = 'center';
  ctx.fillText(text, x, y); ctx.textAlign = 'left';
}

// ---------------------------------------------------------------- title
export function drawTitle(ctx, t) {
  // New style: real Ghibli watercolor backdrop (forest map, cover-fit) under a
  // dark green->indigo wash, so the painted UI reads as part of the world.
  const bg = titleBgImage();
  if (bg) {
    const s = Math.max(VIEW_W / bg.width, VIEW_H / bg.height);
    const w = bg.width * s, h = bg.height * s;
    ctx.drawImage(bg, (VIEW_W - w) / 2, (VIEW_H - h) / 2, w, h);
  } else {
    const g = ctx.createLinearGradient(0, 0, 0, VIEW_H);
    g.addColorStop(0, '#0c1a10'); g.addColorStop(0.6, '#10241a'); g.addColorStop(1, '#1c1230');
    ctx.fillStyle = g; ctx.fillRect(0, 0, VIEW_W, VIEW_H);
  }
  // wash: keep painting visible in the middle, darken top (title) & bottom (footer)
  const wash = ctx.createLinearGradient(0, 0, 0, VIEW_H);
  wash.addColorStop(0, 'rgba(10,20,12,0.82)'); wash.addColorStop(0.35, 'rgba(12,24,16,0.45)');
  wash.addColorStop(0.75, 'rgba(16,14,38,0.55)'); wash.addColorStop(1, 'rgba(16,14,38,0.85)');
  ctx.fillStyle = wash; ctx.fillRect(0, 0, VIEW_W, VIEW_H);

  // drifting fireflies (watercolor-safe: soft, low alpha)
  for (let i = 0; i < 10; i++) {
    const x = (i * 173 + t * (8 + i * 2)) % (VIEW_W + 80) - 40;
    const y = 140 + (i * 97) % 520 + Math.sin(t * 0.9 + i) * 18;
    ctx.globalAlpha = 0.12 + 0.06 * Math.sin(t * 2 + i);
    ctx.fillStyle = i % 3 === 0 ? 'rgba(176,222,255,0.9)' : 'rgba(230,245,205,0.9)';
    ctx.beginPath(); ctx.arc(x, y, 4 + (i % 3) * 3, 0, 7); ctx.fill();
    ctx.globalAlpha = 1;
  }

  // crest: three heroes in the intro pose, on the painting with soft shadows
  // hero painting already shows the three Tribus — no vector sprites on top

  // title plate — Muse watercolor frame (falls back to procedural double line)
  if (!drawSlice(ctx, 'title_frame', VIEW_W / 2 - 400, 90, 800, 170, 32, 0.95)) {
    ctx.save();
    roundRect(ctx, VIEW_W / 2 - 400, 90, 800, 170, 18);
    ctx.fillStyle = 'rgba(18,28,20,0.55)'; ctx.fill();
    ctx.strokeStyle = 'rgba(159,213,168,0.85)'; ctx.lineWidth = 3; ctx.stroke();
    ctx.restore();
  }
  centerText(ctx, 'VERDANT STRUGGLE', VIEW_W / 2, 168, 'bold 58px monospace', PALETTE.paper);
  centerText(ctx, 'explore · battle · capture the three Tribus', VIEW_W / 2, 212, '18px monospace', '#9fd5a8');

  const pulse = 1 + Math.sin(t * 3) * 0.02;
  ctx.save(); ctx.translate(VIEW_W / 2, 300); ctx.scale(pulse, pulse);
  drawHudButton(ctx, -160, -26, 320, 56, '▶  MULAI — PRESS ENTER / CLICK', true);
  ctx.restore();

  centerText(ctx, 'WASD / arrows walk · click sparkles for loot · C = Codex · mouse picks battle actions',
    VIEW_W / 2, 380, '14px monospace', '#a8c4ae');
  centerText(ctx, 'a fully procedural creature quest — art & sound generated by code',
    VIEW_W / 2, VIEW_H - 26, '13px monospace', '#6d8674');
}

// lazy image cache for the title backdrop (module scope so it loads once)
let _titleBg = undefined;
function titleBgImage() {
  if (_titleBg === undefined) {
    _titleBg = null;
    const img = new Image();
    img.onload = () => { _titleBg = img; };
    img.src = 'assets/title_hero.png';
  }
  return _titleBg;
}

export function titleButtonRect() { return { x: VIEW_W / 2 - 160, y: 300 - 26, w: 320, h: 56 }; }

// ---------------------------------------------------------------- battle layout
/** Build the battle action buttons; submenu==='moves' shows the 4 moves instead. */
export function battleButtons(battle, team, submenu) {
  const b = [];
  const x0 = 200, y0 = VIEW_H - 130;
  if (submenu === 'moves') {
    battle.player.moves.forEach((m, i) => {
      const mv = MOVES[m.key];
      b.push({ id: 'move:' + m.key, x: x0 + (i % 2) * 250, y: y0 + Math.floor(i / 2) * 56, w: 236, h: 46,
        label: `${mv.name}`, sub: `${mv.element} · PP ${m.pp}/${mv.pp}` });
    });
    b.push({ id: 'back', x: 1030, y: y0 + 56, w: 140, h: 46, label: '‹ BACK' });
  } else {
    b.push({ id: 'moves', x: x0, y: y0, w: 236, h: 46, label: '⚔ FIGHT', sub: 'choose a move' });
    b.push({ id: 'capture', x: x0 + 250, y: y0, w: 236, h: 46, label: '◎ SEEDSTONE', sub: `× ${team.seedstones}` });
    b.push({ id: 'potion', x: x0, y: y0 + 56, w: 236, h: 46, label: '⚗ MOSSDRA', sub: `× ${team.potions}` });
    b.push({ id: 'switch', x: x0 + 250, y: y0 + 56, w: 236, h: 46, label: '⇄ SWITCH', sub: 'change active' });
    b.push({ id: 'flee', x: 1030, y: y0 + 56, w: 140, h: 46, label: '✕ FLEE' });
  }
  return b;
}

/** Turn a clicked button id into a battle action descriptor (or a submenu change). */
export function battleAction(id, battle, team) {
  if (id && id.startsWith('move:')) return { type: 'move', moveKey: id.slice(5) };
  if (id === 'capture') return team.seedstones > 0 ? { type: 'capture' } : null;
  if (id === 'potion') return team.potions > 0 ? { type: 'potion' } : null;
  if (id === 'flee') return { type: 'flee' };
  return id;
}

// ---------------------------------------------------------------- codex
export function drawCodex(ctx, team, t) {
  ctx.fillStyle = '#0d1512'; ctx.fillRect(0, 0, VIEW_W, VIEW_H);
  panel(ctx, 30, 24, VIEW_W - 60, 68, 0.95);
  centerText(ctx, '◈ THE VERDANT CODEX ◈', VIEW_W / 2, 54, 'bold 30px monospace', PALETTE.paper);
  centerText(ctx, `${team.dexCaught.size} bound · ${team.dexSeen.size} sighted — seen in battle, captured with Seedstones`, VIEW_W / 2, 80, '14px monospace', '#9fb8a6');

  const cols = 4, cellW = 262, cellH = 133, gx = 40, gy = 108;
  SPECIES_LIST.forEach((id, i) => {
    const sp = SPECIES[id];
    const x = gx + (i % cols) * cellW, y = gy + Math.floor(i / cols) * cellH;
    const seen = team.dexSeen.has(id), caught = team.dexCaught.has(id);
    ctx.save();
    ctx.globalAlpha = seen ? 1 : 0.5;
    panel(ctx, x, y, cellW - 16, cellH - 12, 0.9);
    // border glows element colour when caught
    if (caught) {
      ctx.strokeStyle = ELEMENT_COLORS[sp.element].main; ctx.lineWidth = 3;
      roundRect(ctx, x, y, cellW - 16, cellH - 12, 14); ctx.stroke();
    }
    ctx.globalAlpha = seen ? 1 : 0.18;
    drawCreature(ctx, id, x + 58, y + 74, t + i, 'idle');
    ctx.globalAlpha = seen ? 1 : 0.8;
    ctx.fillStyle = PALETTE.paper; ctx.font = 'bold 16px monospace'; ctx.textAlign = 'left';
    ctx.fillText(seen ? sp.name : '???', x + 112, y + 32);
    ctx.font = '11px monospace'; ctx.fillStyle = ELEMENT_COLORS[sp.element].main;
    ctx.fillText(seen ? `${sp.element}${sp.boss ? ' · TRIBUS' : ''}` : 'unknown', x + 112, y + 50);
    if (seen) {
      ctx.fillStyle = '#9fb8a6';
      const words = sp.desc.split(' ');
      let line = '', ly = y + 70;
      for (const w of words) {
        if ((line + w).length > 26) { ctx.fillText(line, x + 112, ly); line = w + ' '; ly += 15; if (ly > y + cellH - 26) break; }
        else line += w + ' ';
      }
      if (ly <= y + cellH - 26) ctx.fillText(line, x + 112, ly);
      ctx.fillStyle = caught ? PALETTE.hpGood : '#6f8577';
      ctx.fillText(caught ? '● bound' : '○ sighted', x + 112, y + cellH - 26);
    }
    ctx.restore();
  });

  // type chart wedge in the right margin
  const cx = gx + cols * cellW + 20;
  panel(ctx, cx, 112, VIEW_W - cx - 40, 420, 0.92);
  centerText(ctx, 'TYPE CHART', cx + 150, 140, 'bold 17px monospace', PALETTE.paper);
  ctx.font = '11px monospace';
  ELEMENTS.forEach((att, r) => {
    ctx.fillStyle = ELEMENT_COLORS[att].main;
    ctx.fillText(`${att.slice(0, 5)} ▸`, cx + 16, 172 + r * 34);
    ELEMENTS.forEach((def, c) => {
      const mult = CHART[att][def];
      ctx.fillStyle = mult > 1 ? '#ff9d76' : mult < 1 ? '#6fae8a' : '#4d5d52';
      ctx.fillText(mult > 1 ? '×2' : mult < 1 ? '×½' : '×1', cx + 84 + c * 30, 172 + r * 34);
    });
  });
  centerText(ctx, 'Ember▸Verdant▸Tide▸Ember', cx + 150, 366, '12px monospace', '#9fb8a6');
  centerText(ctx, 'Volt▸Tide & Gloom', cx + 150, 386, '12px monospace', '#9fb8a6');
  centerText(ctx, 'Gloom▸Verdant', cx + 150, 406, '12px monospace', '#9fb8a6');
  drawSeedstoneIcon(ctx, cx + 150, 446, 22, t);
  centerText(ctx, 'Seedstones bind creatures', cx + 150, 476, '12px monospace', '#9fb8a6');

  drawHudButton(ctx, VIEW_W / 2 - 90, VIEW_H - 66, 180, 44, '‹ BACK (C)', true);
}

